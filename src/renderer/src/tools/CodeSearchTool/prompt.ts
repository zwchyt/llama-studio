export function getCodeSearchPrompt(): string {
  return `# CodeSearch 工具
按自然语言/关键词在代码库内混合检索（词法 + 符号精确，按函数/类逻辑单元分块），返回「文件:起止行 + 符号 + 摘要」。
- 适用：不知道代码在哪个文件时的概念性定位（如「哪里处理流式截断」）；支持中文查询（可命中中文注释）。
- 分工：已知确切标识符/字符串 → Grep；已知文件路径 → Read；看整体结构 → AnalyzeDir。
- 结果只给块摘要；需要细节再对命中文件 Read 对应行段。置信度低时按提示降级，不要反复重试相同查询。`
}
